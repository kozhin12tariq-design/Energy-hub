%% What reactive capability adds ---------------------------------------
% The run above dispatches at UNITY POWER FACTOR. That is not a modelling
% gap any more -- the hub now HAS a reactive variable (see
% multiscale_default_params.m) -- it is what the optimizer chooses when
% nothing asks for voltage support, which is also IEEE 1547's default
% mode. This section asks what the same hub could do for the feeder if
% the voltage floor were actually imposed.
ldfM3 = lindistflow_sensitivity(sysNet);
monM3 = 2:sysNet.nBus;
pQ = p;
pQ.network.enabled = true;  pQ.network.buses = monM3;
pQ.network.C = ldfM3.C(monM3);  pQ.network.a = ldfM3.a(monM3);
pQ.network.b = ldfM3.b(monM3);  pQ.network.Vfloor = ldfM3.Vlin_base(monM3);
solQ = dayahead_dispatch(pQ, fc);
nvQ  = network_verify(sysNet, solQ.Pg_imp - solQ.Pg_exp, struct('dtHours',1.0), solQ.Qh);
solU = dayahead_dispatch(p, fc);
nvU  = network_verify(sysNet, solU.Pg_imp - solU.Pg_exp, struct('dtHours',1.0), solU.Qh);

fprintf('\n--- Reactive power: what the hub can do for voltage (day-ahead) ---\n');
fprintf('Inverter %.1f kVA, IEEE 1547-2018 Cl.5.2 Cat B reactive limit +/-%.1f kvar (44%% of S).\n', ...
    p.Inverter.S_max, p.Inverter.Q_max);
fprintf('%-32s %16s %16s\n', '', 'unity pf', 'voltage support');
fprintf('%-32s %16.2f %16.2f\n', 'Peak Q injected (kvar)', max(solU.Qh), max(solQ.Qh));
fprintf('%-32s %16.2f %16.2f\n', 'Peak active import (kW)', max(solU.Pg_imp), max(solQ.Pg_imp));
fprintf('%-32s %16.4f %16.4f\n', 'Exact min voltage (pu)', nvU.minV, nvQ.minV);
fprintf('%-32s %16.4f %16.4f\n', 'Feeder losses (kWh/day)', nvU.lossEnergy_kWh, nvQ.lossEnergy_kWh);
fprintf('%-32s %16.4f %16.4f\n', 'Day-ahead cost ($)', solU.cost, solQ.cost);
fprintf('%-32s %16.4f %16s\n', 'No-hub base min V (pu)', nvU.base_minV, '(reference)');

