%% Which generalized storage mechanisms actually contributed? ----------
% The SOC ranges above are not the same thing as CONTRIBUTION: a device
% can move once and then sit still. Energy actually cycled per day is the
% honest measure, and on this profile the two "generalized storage"
% mechanisms named in the roadmap do NOT both deliver. Reported here
% rather than left for a reader to notice.
cycled = @(soc, Emax) sum(max(diff(soc), 0)) * Emax;   % kWh charged over the day
thBld  = cycled(res.ID_SOC.Building, p.Building.Emax);
thPipe = cycled(res.ID_SOC.Pipe,     p.Pipe.Emax);

% Counterfactual: remove the pipe and see whether the building CAN work.
% This distinguishes "incapable" from "displaced by something better".
pNoPipe = p;
pNoPipe.Pipe.Pch_max = 0; pNoPipe.Pipe.Pdis_max = 0;
resNoPipe = simulate_multiscale_day(pNoPipe, fc, struct('useIntraday', true, 'reserveScale', 1.0));

shift6 = @(d) d.eta_ch * d.eta_dis * (1 - d.selfLoss)^6;   % 6h round-trip retention

fprintf('\n--- Generalized storage: which mechanisms actually contributed? ---\n');
fprintf('%-26s %14s %14s\n', '', 'Building mass', 'Pipe network');
fprintf('%-26s %14.2f %14.2f\n', 'Energy cycled (kWh/day)', thBld, thPipe);
fprintf('%-26s %14.3f %14.3f\n', 'SOC range used', ...
    max(res.ID_SOC.Building)-min(res.ID_SOC.Building), max(res.ID_SOC.Pipe)-min(res.ID_SOC.Pipe));
fprintf('%-26s %14.1f %14.1f\n', 'Capacity (kWh)', p.Building.Emax, p.Pipe.Emax);
fprintf('%-26s %14.3f %14.3f\n', 'Round-trip efficiency', ...
    p.Building.eta_ch*p.Building.eta_dis, p.Pipe.eta_ch*p.Pipe.eta_dis);
fprintf('%-26s %14.3f %14.3f\n', 'Retention over 6 h', ...
    (1-p.Building.selfLoss)^6, (1-p.Pipe.selfLoss)^6);
fprintf('%-26s %14.3f %14.3f\n', '6h shift effectiveness', shift6(p.Building), shift6(p.Pipe));

fprintf(['\nONLY ONE OF THE TWO DELIVERS ON THIS PROFILE. The pipe network cycles\n' ...
